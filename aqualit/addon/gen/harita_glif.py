def yazi_ciz(img, x0, y0, metin, renk, o=1):
    """metni (x0, y0) üst-sol köşeye 3x5 harfle (o kat büyük) çizer (aksanlar dahil); genişliği döner."""
    def nokta(px, py):
        for a in range(o):
            for b in range(o):
                img.putpixel((px * 1 + a, py * 1 + b), renk)
    x = x0
    for ch in metin:
        taban, ust, alt = AKSAN.get(ch, (ch, None, None))
        g = FONT.get(taban, FONT[' '])
        w = len(g[0])
        for yy, satir in enumerate(g):
            for xx, c in enumerate(satir):
                if c == '#':
                    nokta(x + xx * o, y0 + (1 + yy) * o)
        if ust == 'nokta' or ust == 'şapka':
            nokta(x + 1 * o, y0)
        elif ust == 'iki':
            nokta(x, y0); nokta(x + 2 * o, y0)
        if alt:
            nokta(x + 1 * o, y0 + 6 * o)
        x += (w + 1) * o
    return x - x0 - o


def yazi_genislik(metin, o=1):
    return (sum(len(FONT.get(AKSAN.get(c, (c,))[0], FONT[' '])[0]) + 1 for c in metin) - 1) * o


